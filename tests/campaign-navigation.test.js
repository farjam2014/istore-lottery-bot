import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const sourcePath=fileURLToPath(new URL('../src/bot/handlers/admin.handler.js',import.meta.url));
const source=readFileSync(sourcePath,'utf8');

test('campaign detail callback matches the IDs generated by the campaign list',()=>{
  assert.ok(source.includes(String.raw`bot.action(/^admin:campaign:detail:(\d+)$/`),
    'campaign detail handler must use a digit matcher, not a literal backslash');
  const route=/^admin:campaign:detail:(\d+)$/;
  assert.deepEqual('admin:campaign:detail:42'.match(route)?.[1],'42');
  assert.equal('admin:campaign:detail:\\d+'.match(route),null);
});

test('campaign pagination callback matches generated page numbers',()=>{
  assert.ok(source.includes(String.raw`bot.action(/^admin:campaign:list:page:(\d+)$/`),
    'campaign pagination handler must use a digit matcher');
  const route=/^admin:campaign:list:page:(\d+)$/;
  assert.deepEqual('admin:campaign:list:page:3'.match(route)?.[1],'3');
});
